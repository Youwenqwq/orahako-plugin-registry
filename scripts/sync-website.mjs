import fs from "node:fs"
import path from "node:path"
import { REPO_ROOT, buildIndex, serializeJson } from "./lib/registry.mjs"
import { reportError } from "./lib/rules.mjs"

const DEFAULT_TARGET = path.resolve(
  REPO_ROOT,
  "..",
  "ysu-client",
  "website",
  "edge-functions",
  "updates",
  "plugins.json.js"
)

const HEADER = `// @generated by orahako-plugin-registry — do not edit by hand.
// Registry: https://github.com/Youwenqwq/orahako-plugin-registry
// Served to the public client from https://ysu.welain.com/updates/plugins.json.
// Regenerate with: pnpm run sync:website
`

/**
 * Render the deployment snapshot consumed by the public website.
 *
 * The JSON body is the generated public index, so internal registry fields
 * (`repository`, `sourcePath`, `trust`, `order`) are never part of the
 * snapshot. GET/CORS/no-cache and OPTIONS behavior is preserved from the
 * hand-written edge function.
 */
function renderWebsiteModule(index) {
  return `${HEADER}
const DEFAULT_INDEX = ${serializeJson(index).trimEnd()}

const HEADERS = {
  "content-type": "application/json; charset=utf-8",
  "Access-Control-Allow-Origin": "*",
  "Cache-Control": "no-cache",
}

function json(value) {
  return new Response(JSON.stringify(value), { headers: HEADERS })
}

export function onRequestGet() {
  return json(DEFAULT_INDEX)
}

export async function onRequestOptions() {
  return new Response(null, {
    headers: {
      "Access-Control-Allow-Origin": "*",
      "Access-Control-Allow-Methods": "GET, OPTIONS",
      "Access-Control-Allow-Headers": "Content-Type",
    },
  })
}
`
}

function parseArgs(argv) {
  let target = process.env.REGISTRY_WEBSITE_INDEX ?? DEFAULT_TARGET
  let check = false
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === "--check") {
      check = true
    } else if (arg === "--out") {
      index += 1
      target = argv[index]
      if (target === undefined || target.length === 0) throw new Error("--out requires a path")
    } else if (arg.startsWith("--out=")) {
      target = arg.slice("--out=".length)
    } else {
      throw new Error(`unknown argument: ${arg}`)
    }
  }
  return { target: path.resolve(target), check }
}

function main() {
  const { target, check } = parseArgs(process.argv.slice(2))
  const text = renderWebsiteModule(buildIndex())
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : undefined

  if (current === text) {
    console.log(`Website snapshot is up to date: ${target}`)
    return
  }
  if (check) {
    console.error(`error: ${target} is out of date; run pnpm run sync:website`)
    process.exitCode = 1
    return
  }

  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, text)
  console.log(`Wrote website snapshot: ${target}`)
}

try {
  main()
} catch (error) {
  reportError(error)
}
